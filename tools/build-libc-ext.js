#!/usr/bin/env node
// Generate libc-ext.js — the OPTIONAL extension library for compiler.js.
//
// Reads the headers in ext/include/ and the source files in ext/src/ and emits
// a single `libc-ext.js` at the repo root containing a JSON-parseable
//   const EXT_LIB_MAP = { "<name>": "<file text>", ... };
// keyed by basename. compiler.js loads this file if it sits next to it (see
// getExtLibMap()); the compiler is fully functional without it.
//
// Run from the repo root:  node tools/build-libc-ext.js
//
// Do NOT hand-edit libc-ext.js — edit ext/ and regenerate.

const fs = require("fs");
const path = require("path");

// Cross-tree preflight (todos/0341, extended by #142): emits libc-ext.js at
// its own repo root — a self-tree writer the #142 survey found missing from
// the original list. No harness spawns — hand-run only.
require(path.join(__dirname, "../tests/lib/tree-guard.js"))
  .assertSameTree(__dirname, { label: "tools/build-libc-ext.js" });

const ROOT = path.resolve(__dirname, "..");
const DIRS = [path.join(ROOT, "ext", "include"), path.join(ROOT, "ext", "src")];
const OUT = path.join(ROOT, "libc-ext.js");

const map = {};
for (const dir of DIRS) {
  for (const entry of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, entry);
    if (!fs.statSync(full).isFile()) continue;
    if (map[entry] !== undefined) {
      throw new Error(`duplicate ext entry name: ${entry}`);
    }
    map[entry] = fs.readFileSync(full, "utf-8");
  }
}

// Keys sorted for stable diffs. The header comment is deliberately brace-free
// so compiler.js can extract the object with slice(indexOf('{'), lastIndexOf('}')).
const sorted = {};
for (const k of Object.keys(map).sort()) sorted[k] = map[k];

const banner =
  "// libc-ext.js — GENERATED by tools/build-libc-ext.js from ext/. Do not edit.\n" +
  "// Optional extension library for compiler.js: POSIX/3rd-party libc pieces\n" +
  "// (TRE regex, fnmatch, glob, search.h) too big to inline. compiler.js works\n" +
  "// without it. Licenses: TRE (reg*/tre*) is 2-clause BSD (c) Ville Laurikari;\n" +
  "// fnmatch/glob and the search.h family are MIT (c) musl contributors. See\n" +
  "// ext/README.md.\n";

const body =
  banner +
  "const EXT_LIB_MAP = " + JSON.stringify(sorted) + ";\n" +
  "if (typeof globalThis !== 'undefined') globalThis.EXT_LIB_MAP = EXT_LIB_MAP;\n";

fs.writeFileSync(OUT, body);

const names = Object.keys(sorted);
const bytes = Buffer.byteLength(body);
process.stdout.write(
  `wrote ${path.relative(ROOT, OUT)} — ${names.length} entries, ${(bytes / 1024).toFixed(1)} KB\n` +
  `  ${names.join(", ")}\n`,
);
